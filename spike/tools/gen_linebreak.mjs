// Generates spike/kernel/src/linebreak_data.rs: the Line_Break class of every scalar value
// (Unicode 16.0), already resolved by rule LB1 of UAX #14, with the two other facts its
// rules use. Run: node gen_linebreak.mjs   (after `npm install` here).
// Line_Break, General_Category and Extended_Pictographic come from the npm package
// @unicode/unicode-16.0.0. That package has no East_Asian_Width: it is read from
// ucd/EastAsianWidth.txt (EastAsianWidth-16.0.0.txt of the Unicode Character Database).
import fs from 'fs';
const U = '@unicode/unicode-16.0.0/';
const load = async p => (await import(U + p + '/ranges.mjs')).default;
const here = new URL('.', import.meta.url);
const NAMES = { BK: 'Mandatory_Break', CR: 'Carriage_Return', LF: 'Line_Feed', CM: 'Combining_Mark', NL: 'Next_Line', WJ: 'Word_Joiner', ZW: 'ZWSpace', GL: 'Glue', SP: 'Space', ZWJ: 'ZWJ',
  B2: 'Break_Both', BA: 'Break_After', BB: 'Break_Before', HY: 'Hyphen', CB: 'Contingent_Break', CL: 'Close_Punctuation', CP: 'Close_Parenthesis', EX: 'Exclamation', IN: 'Inseparable',
  NS: 'Nonstarter', OP: 'Open_Punctuation', QU: 'Quotation', IS: 'Infix_Numeric', NU: 'Numeric', PO: 'Postfix_Numeric', PR: 'Prefix_Numeric', SY: 'Break_Symbols', AK: 'Aksara', AL: 'Alphabetic',
  AP: 'Aksara_Prebase', AS: 'Aksara_Start', EB: 'E_Base', EM: 'E_Modifier', H2: 'H2', H3: 'H3', HL: 'Hebrew_Letter', ID: 'Ideographic', JL: 'JL', JV: 'JV', JT: 'JT', RI: 'Regional_Indicator',
  VF: 'Virama_Final', VI: 'Virama' };
const CLASSES = [...Object.keys(NAMES), 'QI', 'QF'];   // QI, QF: QU that is also Pi, Pf (LB15a, LB15b, LB19)
const UNRESOLVED = { AI: 'Ambiguous', SG: 'Surrogate', XX: 'Unknown', SA: 'Complex_Context', CJ: 'Conditional_Japanese_Starter' };
const N = 0x110000, val = new Uint8Array(N).fill(CLASSES.indexOf('AL'));   // LB1: XX and what nothing lists are AL
const mark = async (p, f) => { for (const r of await load(p)) for (let c = r.begin; c < r.end; c++) f(c); };
for (const [k, n] of Object.entries(NAMES)) await mark('Line_Break/' + n, c => val[c] = CLASSES.indexOf(k));
const gc = new Uint8Array(N);   // 1 Mn or Mc, 2 Pi, 3 Pf, 4 Cn
for (const [n, v] of [['Nonspacing_Mark', 1], ['Spacing_Mark', 1], ['Initial_Punctuation', 2], ['Final_Punctuation', 3], ['Unassigned', 4]]) await mark('General_Category/' + n, c => gc[c] = v);
await mark('Line_Break/' + UNRESOLVED.SA, c => val[c] = CLASSES.indexOf(gc[c] === 1 ? 'CM' : 'AL'));   // LB1
await mark('Line_Break/' + UNRESOLVED.CJ, c => val[c] = CLASSES.indexOf('NS'));
for (const k of ['AI', 'SG', 'XX']) await mark('Line_Break/' + UNRESOLVED[k], c => val[c] = CLASSES.indexOf('AL'));
for (let c = 0; c < N; c++) if (val[c] === CLASSES.indexOf('QU') && gc[c] >= 2 && gc[c] <= 3) val[c] = CLASSES.indexOf(gc[c] === 2 ? 'QI' : 'QF');
// bit 6: East_Asian_Width is F, W or H (LB19a, LB21a, LB30)
for (const line of fs.readFileSync(new URL('ucd/EastAsianWidth.txt', here), 'utf8').split('\n')) {
  const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line); if (!m || !'FWH'.includes(m[3])) continue;
  for (let c = parseInt(m[1], 16); c <= parseInt(m[2] || m[1], 16); c++) val[c] |= 64;
}
// bit 7: Extended_Pictographic and unassigned (LB30b)
await mark('Binary_Property/Extended_Pictographic', c => { if (gc[c] === 4) val[c] |= 128; });
const runs = []; let last = -1;
for (let c = 0; c < N; c++) { if (c >= 0xD800 && c < 0xE000) continue; if (val[c] !== last) { runs.push([c, last = val[c]]); } }
let out = '// Generated by spike/tools/gen_linebreak.mjs from Unicode 16.0 data. Do not edit.\n';
out += '// Each entry: the first scalar value of a run, shifted left 8, with the run\'s value: bits 0 to 5 the\n// Line_Break class after LB1, bit 6 East_Asian_Width F, W or H, bit 7 Extended_Pictographic and unassigned.\n';
CLASSES.forEach((k, i) => out += `pub const ${k}: u8 = ${i};\n`);
out += `pub static RUNS: [u32; ${runs.length}] = [`;
runs.forEach(([c, v], i) => out += (i % 12 ? ' ' : '\n    ') + '0x' + (c * 256 + v).toString(16) + ',');
out += '\n];\n';
fs.writeFileSync(new URL('../kernel/src/linebreak_data.rs', here), out);
console.log('classes', CLASSES.length, 'runs', runs.length, 'table bytes', runs.length * 4);
